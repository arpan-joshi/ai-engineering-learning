import numpy as np


# Discrete random variable
# X represents the result of rolling a dice

dice_outcomes = np.array([1, 2, 3, 4, 5, 6])

print("Dice outcomes:")
print(dice_outcomes)


# Continuous random variable
# Example: height

heights = np.array([
    165.2,
    170.5,
    172.1,
    168.4,
    175.3
])

print("\nHeight values:")
print(heights)