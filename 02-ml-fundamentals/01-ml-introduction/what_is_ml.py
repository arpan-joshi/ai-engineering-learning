# What is Machine Learning?

# Traditional programming:
# Input + Rules -> Output

# Machine Learning:
# Input + Examples -> Learned Model

# Example: Predicting house prices

# Features (input):
area = 1200
bedrooms = 2

# A simple illustrative prediction rule
price = 3000 * area + 200000 * bedrooms

print("Area:", area, "sq ft")
print("Bedrooms:", bedrooms)
print("Illustrative predicted price:", price)